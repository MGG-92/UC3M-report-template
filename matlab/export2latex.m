function export2latex(values, options)
% EXPORT2LATEX Export a struct of numeric scalars as LaTeX commands.
%   export2latex(filename="results.tex")             % Reset only.
%   export2latex(struct('Force',F), filename="results.tex")
%   export2latex(values, settings=s, precision=17, reset=true)
% Options: filename (results.tex), precision (12), reset (false), settings.
% Explicit options override settings; other fields use defaults.
% Without values, reset the file. With values, append unless reset=true.
% Field names contain letters only. Values must be finite real scalars.
% Field 'Force' creates \MATForce containing \num; load siunitx.

arguments
    values (1,1) struct = struct()
    options.settings (1,1) struct = struct()
    options.filename
    options.precision
    options.reset
end

combined = options.settings;
names = fieldnames(rmfield(options,'settings'));
for k = 1:numel(names)
    combined.(names{k}) = options.(names{k});
end
args = namedargs2cell(combined);
config = validate_options(args{:});
filename = char(config.filename);
names = fieldnames(values);

% Validate all data before resetting or modifying the output file.
for k = 1:numel(names)
    value = values.(names{k});
    if isempty(regexp(names{k},'^[a-zA-Z]+$','once'))
        error('export2latex:Name','Names must contain letters only.');
    end
    if ~isnumeric(value) || ~isscalar(value) || ~isreal(value) || ~isfinite(value)
        error('export2latex:Value','Values must be finite real numeric scalars.');
    end
end

if config.reset || isempty(names)
    fid = fopen(filename,'w');
    if fid==-1, error('export2latex:File','Cannot open file: %s',filename); end
    fprintf(fid,'%% Auto-generated by MATLAB\n');
    fclose(fid);
    if isempty(names), return; end
end

% Read existing definitions
existing = '';
if isfile(filename)
    existing = fileread(filename);
end

lines = {};

for k = 1:numel(names)

    name = names{k};
    value = values.(name);

    % Use MAT prefix to avoid collisions with LaTeX commands
    macro = ['MAT', name];

    % Check for existing definition
    alreadyExists = ...
        contains(existing, sprintf('\\newcommand{\\%s}', macro)) || ...
        contains(existing, sprintf('\\renewcommand{\\%s}', macro));

    if alreadyExists
        warning('export2latex:Duplicate', ...
            'Variable "%s" already exists. Updating value.', name);
        command = 'renewcommand';
    else
        command = 'newcommand';
    end

    % Round only the exported representation.
    formatted = sprintf('%.*g',config.precision,value);

    % Generate LaTeX definition
    line = sprintf('\\%s{\\%s}{\\num{%s}}\n', ...
        command, macro, formatted);

    lines{end+1} = line;

    % Update local definitions for duplicates in the same call
    existing = [existing, line];
end

% Append without deleting previous definitions
fid = fopen(filename, 'a');

if fid == -1
    error('Cannot open file: %s', filename);
end

fprintf(fid, '%s', [lines{:}]);
fclose(fid);
end

function config = validate_options(config)
arguments
    config.filename (1,1) string {mustBeNonzeroLengthText} = "results.tex"
    config.precision (1,1) double {mustBeReal,mustBeFinite,mustBeInteger, ...
        mustBePositive,mustBeLessThanOrEqual(config.precision,17)} = 12
    config.reset (1,1) logical = false
end
end
