function export2latex(filename, varargin)
% EXPORT2LATEX Export MATLAB variables to a LaTeX file.
%
% Initialize (clears the file):
%   export2latex("results.tex")
%
% Add or update variables:
%   export2latex("results.tex", "name1", value1, ...)
%
% Duplicate names generate a warning and are redefined.
% Only finite, real numeric scalars are supported.
% Names contain letters only; name 'Force' creates the command \MATForce.
% Commands wrap their value in \num (12 significant digits); load siunitx.
% Reset once per script run, export values, then rerun LaTeX to update them.
% The destination folder must already exist.

    filename = char(filename);

    % Initialize / reset file
    if isempty(varargin)
        fid = fopen(filename, 'w');
        if fid == -1
            error('Cannot open file: %s', filename);
        end

        fprintf(fid, '%% Auto-generated by MATLAB\n');
        fclose(fid);
        return;
    end

    % Validate number of arguments
    if mod(numel(varargin), 2) ~= 0
        error('Arguments must be name-value pairs.');
    end

    % Read existing definitions
    existing = '';
    if isfile(filename)
        existing = fileread(filename);
    end

    lines = {};

    for k = 1:2:numel(varargin)

        name = char(varargin{k});
        value = varargin{k+1};

        % Validate LaTeX command name
        if isempty(regexp(name, '^[a-zA-Z]+$', 'once'))
            error('Invalid variable name: %s', name);
        end

        % Validate value
        if ~isnumeric(value) || ~isscalar(value) || ...
                ~isreal(value) || ~isfinite(value)
            error('Variable %s must be a finite real scalar.', name);
        end

        % Use MAT prefix to avoid collisions with LaTeX commands
        macro = ['MAT', name];

        % Check for existing definition
        alreadyExists = ...
            contains(existing, sprintf('\\newcommand{\\%s}', macro)) || ...
            contains(existing, sprintf('\\renewcommand{\\%s}', macro));

        if alreadyExists
            warning('export2latex:Duplicate', ...
                'Variable "%s" already exists. Updating value.', name);
            command = 'renewcommand';
        else
            command = 'newcommand';
        end

        % Format with 12 significant digits
        formatted = sprintf('%.12g', value);

        % Generate LaTeX definition
        line = sprintf('\\%s{\\%s}{\\num{%s}}\n', ...
            command, macro, formatted);

        lines{end+1} = line;

        % Update local definitions for duplicates in the same call
        existing = [existing, line];
    end

    % Append without deleting previous definitions
    fid = fopen(filename, 'a');

    if fid == -1
        error('Cannot open file: %s', filename);
    end

    fprintf(fid, '%s', [lines{:}]);
    fclose(fid);
end
